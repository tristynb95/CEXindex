// Resolution runs seven regexes over the name and is the innermost call in every
// region/ops filter, so the dashboard reaches it a few times per record per
// pass. The answer only depends on the name and the alias lookups, and those are
// rebuilt in exactly one place, so cache it and clear the cache there.
var _bakeryMetaKeyCache = Object.create(null);

window.GAILS.resolveBakeryMetaKey = function (name) {
  var trimmed = String(name == null ? '' : name).trim();
  if (!trimmed) return '';

  var cached = _bakeryMetaKeyCache[trimmed];
  if (cached !== undefined) return cached;

  var resolved;
  if ((window.GAILS.BAKERY_META && window.GAILS.BAKERY_META[trimmed]) ||
      (window.GAILS.DEFAULT_BAKERY_META && window.GAILS.DEFAULT_BAKERY_META[trimmed])) {
    resolved = trimmed;
  } else {
    var normalized = _normalizeBakeryLookupName(trimmed);
    var direct = _BAKERY_EXTRA_ALIASES[normalized] ||
      _bakeryMetaAliasLookup[normalized] || _defaultBakeryAliasLookup[normalized];
    if (direct) {
      resolved = direct;
    } else {
      var collapsed = normalized.replace(/\s+/g, '');
      resolved = _bakeryMetaCollapsedAliasLookup[collapsed] ||
        _defaultBakeryCollapsedAliasLookup[collapsed] || trimmed;
    }
  }

  _bakeryMetaKeyCache[trimmed] = resolved;
  return resolved;
};

window.GAILS.getBakeryMeta = function (name) {
  var key = window.GAILS.resolveBakeryMetaKey(name);
  if (!key) return null;

  // The live site directory can briefly lag behind newly opened bakeries. Keep
  // the built-in directory as a coordinate/ownership fallback so a valid site
  // does not disappear from maps just because it is absent from that payload.
  return (window.GAILS.BAKERY_META && window.GAILS.BAKERY_META[key]) ||
    (window.GAILS.DEFAULT_BAKERY_META && window.GAILS.DEFAULT_BAKERY_META[key]) ||
    null;
};

window.GAILS.getBakeryMapLabel = function (name) {
  var text = String(name == null ? '' : name).trim();
  if (!text) return '';
  if (/^gail[\'’]?s\b/i.test(text)) return text;

  var meta = window.GAILS.getBakeryMeta(text);
  if (meta && meta.dn) return meta.dn;

  var key = window.GAILS.resolveBakeryMetaKey(text);
  return key ? "GAIL's " + key : text;
};

window.GAILS.cloneBakeryMeta = function (meta) {
  var source = meta && typeof meta === 'object' ? meta : {};
  var cloned = {};
  Object.keys(source).sort().forEach(function (name) {
    var trimmedName = String(name == null ? '' : name).trim();
    if (!trimmedName) return;

    var canonicalName = window.GAILS.resolveBakeryMetaKey(trimmedName) || trimmedName;
    var entry = source[name] || {};
    var existing = cloned[canonicalName] || {};
    var fallback = window.GAILS.DEFAULT_BAKERY_META[canonicalName] || null;
    var displayName = entry.dn ? String(entry.dn).trim() : trimmedName;
    var entryR = entry.r ? String(entry.r).trim() : '';
    var entryO = entry.o ? String(entry.o).trim() : '';
    cloned[canonicalName] = {
      r: (entryR && entryR !== 'Unknown') ? entryR : ((existing.r && existing.r !== 'Unknown') ? existing.r : (fallback ? fallback.r : 'Unknown')),
      o: (entryO && entryO !== 'Unknown') ? entryO : ((existing.o && existing.o !== 'Unknown') ? existing.o : (fallback ? fallback.o : 'Unknown')),
      ll: Array.isArray(entry.ll) ? entry.ll : (existing.ll || (fallback && Array.isArray(fallback.ll) ? fallback.ll : null))
    };
    if (displayName && displayName !== canonicalName) {
      cloned[canonicalName].dn = displayName;
    } else if (existing.dn) {
      cloned[canonicalName].dn = existing.dn;
    }
  });
  return cloned;
};

window.GAILS.setBakeryMeta = function (meta) {
  var fallback = window.GAILS.DEFAULT_BAKERY_META || {};
  window.GAILS.BAKERY_META = window.GAILS.cloneBakeryMeta(meta && Object.keys(meta).length ? meta : fallback);
  _bakeryMetaAliasLookup = _buildBakeryAliasLookup(fallback, window.GAILS.BAKERY_META);
  _bakeryMetaCollapsedAliasLookup = _buildBakeryCollapsedAliasLookup(fallback, window.GAILS.BAKERY_META);
  // Cleared last, not first: cloneBakeryMeta above resolves names itself, against
  // the outgoing directory, so anything it cached has to be thrown away too.
  _bakeryMetaKeyCache = Object.create(null);
  // Everything else that memoises a *resolved* bakery name is stale for the
  // same reason. These are optional so pages that don't load those files (or
  // load them after this one) still work.
  if (typeof window.GAILS.invalidateVisitPeriodIndex === 'function') {
    window.GAILS.invalidateVisitPeriodIndex();
  }
  if (typeof window.GAILS.invalidateFocusDataset === 'function') {
    window.GAILS.invalidateFocusDataset();
  }
  if (typeof window.GAILS.onBakeryMetaChanged === 'function') {
    window.GAILS.onBakeryMetaChanged(window.GAILS.BAKERY_META);
  }
  return window.GAILS.BAKERY_META;
};

window.GAILS.getBakeryMetaSnapshot = function () {
  return window.GAILS.cloneBakeryMeta(window.GAILS.BAKERY_META);
};

function _normalizeRegionAssignmentKey(value) {
  return String(value == null ? '' : value).trim().replace(/\s+/g, ' ').toLowerCase();
}

// A region on cover has its Coffee Partner and Coffee Trainer named per ops
// area instead of once for the whole region — what happens while one of them
// has left and their patch is split between colleagues. Areas nobody covers,
// and every region not on cover, still fall back to the region's own pair. See
// js/region-assignments.js, where the admin maintains this.
function _normalizeRegionCover(value) {
  var source = value && typeof value === 'object' ? value : {};
  var areas = Array.isArray(source.areas) ? source.areas : [];
  return {
    enabled: source.enabled === true || source.enabled === 'true',
    areas: areas.map(function (entry) {
      var record = entry && typeof entry === 'object' ? entry : {};
      return {
        opsArea: String(record.opsArea || '').trim().replace(/\s+/g, ' '),
        coffeePartner: String(record.coffeePartner || '').trim(),
        coffeePartnerUid: String(record.coffeePartnerUid || '').trim(),
        coffeeTrainer: String(record.coffeeTrainer || '').trim(),
        coffeeTrainerUid: String(record.coffeeTrainerUid || '').trim()
      };
    }).filter(function (area) {
      return !!area.opsArea &&
        !!(area.coffeePartner || area.coffeePartnerUid ||
           area.coffeeTrainer || area.coffeeTrainerUid);
    })
  };
}

function _cloneRegionCover(cover) {
  return {
    enabled: cover.enabled,
    areas: cover.areas.map(function (area) {
      return {
        opsArea: area.opsArea,
        coffeePartner: area.coffeePartner,
        coffeePartnerUid: area.coffeePartnerUid,
        coffeeTrainer: area.coffeeTrainer,
        coffeeTrainerUid: area.coffeeTrainerUid
      };
    })
  };
}

// Coffee Partner and Coffee Trainer ownership is maintained once per region
// in the admin site directory. Keep a normalized lookup alongside the public
// snapshot so any bakery-facing view can resolve those names consistently,
// even when an uploaded workbook varies the region's case or spacing.
window.GAILS.setRegionAssignments = function (assignments) {
  var source = Array.isArray(assignments)
    ? assignments
    : Object.values(assignments && typeof assignments === 'object' ? assignments : {});
  var records = [];
  var lookup = {};

  source.forEach(function (record) {
    var region = String(record && record.region || '').trim().replace(/\s+/g, ' ');
    if (!region) return;
    var normalized = {
      region: region,
      coffeePartner: String(record && record.coffeePartner || '').trim(),
      coffeePartnerUid: String(record && record.coffeePartnerUid || '').trim(),
      coffeeTrainer: String(record && record.coffeeTrainer || '').trim(),
      coffeeTrainerUid: String(record && record.coffeeTrainerUid || '').trim(),
      cover: _normalizeRegionCover(record && record.cover)
    };
    records.push(normalized);
    lookup[_normalizeRegionAssignmentKey(region)] = normalized;
  });

  records.sort(function (a, b) { return a.region.localeCompare(b.region); });
  window.GAILS.REGION_ASSIGNMENTS = records;
  window.GAILS._regionAssignmentLookup = lookup;
  return records;
};

// Pass the bakery's ops area to get the pair who actually look after it. The
// two roles resolve independently, so a region can split its Coffee Partner
// patch while the same Coffee Trainer carries on across all of it.
window.GAILS.getRegionAssignment = function (region, opsArea) {
  var key = _normalizeRegionAssignmentKey(region);
  var record = key && window.GAILS._regionAssignmentLookup
    ? window.GAILS._regionAssignmentLookup[key]
    : null;
  if (!record) return null;

  var resolved = {
    region: record.region,
    coffeePartner: record.coffeePartner,
    coffeeTrainer: record.coffeeTrainer,
    coverEnabled: record.cover.enabled,
    partnerFromCover: false,
    trainerFromCover: false
  };
  if (!record.cover.enabled) return resolved;

  var areaKey = _normalizeRegionAssignmentKey(opsArea);
  var area = areaKey && record.cover.areas.filter(function (entry) {
    return _normalizeRegionAssignmentKey(entry.opsArea) === areaKey;
  })[0];
  if (!area) return resolved;

  if (area.coffeePartner || area.coffeePartnerUid) {
    resolved.coffeePartner = area.coffeePartner;
    resolved.partnerFromCover = true;
  }
  if (area.coffeeTrainer || area.coffeeTrainerUid) {
    resolved.coffeeTrainer = area.coffeeTrainer;
    resolved.trainerFromCover = true;
  }
  return resolved;
};

window.GAILS.getRegionAssignmentsSnapshot = function () {
  return (window.GAILS.REGION_ASSIGNMENTS || []).map(function (record) {
    return {
      region: record.region,
      coffeePartner: record.coffeePartner,
      coffeePartnerUid: record.coffeePartnerUid,
      coffeeTrainer: record.coffeeTrainer,
      coffeeTrainerUid: record.coffeeTrainerUid,
      cover: _cloneRegionCover(record.cover)
    };
  });
};

// Area Head Barista ownership is maintained once per ops area in the admin
// site directory. Ops area names are only guaranteed unique inside their own
// region, so the primary lookup is keyed on the pair. A second lookup on the
// ops area alone lets a caller that only knows the bakery's ops area resolve
// it too — but only while that name is unambiguous across regions, so a
// duplicated ops area name can never hand back the wrong region's barista.
window.GAILS.setOpsAreaAssignments = function (assignments) {
  var source = Array.isArray(assignments)
    ? assignments
    : Object.values(assignments && typeof assignments === 'object' ? assignments : {});
  var records = [];
  var lookup = {};
  var opsOnlyLookup = {};
  var ambiguousOpsAreas = {};

  source.forEach(function (record) {
    var opsArea = String(record && record.opsArea || '').trim().replace(/\s+/g, ' ');
    if (!opsArea) return;
    var region = String(record && record.region || '').trim().replace(/\s+/g, ' ');

    var baristas = (Array.isArray(record && record.baristas) ? record.baristas : [])
      .map(function (entry) {
        var value = entry && typeof entry === 'object' ? entry : {};
        return {
          name: String(value.name || '').trim(),
          uid: String(value.uid || '').trim(),
          homeBakery: String(value.homeBakery || '').trim()
        };
      }).filter(function (entry) { return !!(entry.name || entry.homeBakery); });

    // An ops area saved before it could hold more than one area head barista
    // reads as a single entry.
    if (!baristas.length && record && (record.areaHeadBarista || record.homeBakery)) {
      baristas = [{
        name: String(record.areaHeadBarista || '').trim(),
        uid: String(record.areaHeadBaristaUid || '').trim(),
        homeBakery: String(record.homeBakery || '').trim()
      }];
    }

    var named = baristas.filter(function (entry) { return !!entry.name; });
    var normalized = {
      region: region,
      opsArea: opsArea,
      baristas: baristas,
      // Flattened for the many read-only surfaces that just want to print who
      // looks after an ops area.
      areaHeadBarista: named.map(function (entry) { return entry.name; }).join(' · '),
      areaHeadBaristaUid: named.length === 1 ? named[0].uid : '',
      homeBakery: named.length === 1 ? named[0].homeBakery : ''
    };
    records.push(normalized);

    var opsKey = _normalizeRegionAssignmentKey(opsArea);
    lookup[_normalizeRegionAssignmentKey(region) + ' ' + opsKey] = normalized;
    if (Object.prototype.hasOwnProperty.call(opsOnlyLookup, opsKey)) {
      ambiguousOpsAreas[opsKey] = true;
    } else {
      opsOnlyLookup[opsKey] = normalized;
    }
  });

  Object.keys(ambiguousOpsAreas).forEach(function (key) {
    delete opsOnlyLookup[key];
  });

  records.sort(function (a, b) {
    return a.region.localeCompare(b.region) || a.opsArea.localeCompare(b.opsArea);
  });
  window.GAILS.OPS_AREA_ASSIGNMENTS = records;
  window.GAILS._opsAreaAssignmentLookup = lookup;
  window.GAILS._opsAreaOnlyAssignmentLookup = opsOnlyLookup;
  return records;
};

window.GAILS.getOpsAreaAssignment = function (opsArea, region) {
  var opsKey = _normalizeRegionAssignmentKey(opsArea);
  if (!opsKey) return null;
  var record = null;
  if (region && window.GAILS._opsAreaAssignmentLookup) {
    record = window.GAILS._opsAreaAssignmentLookup[
      _normalizeRegionAssignmentKey(region) + ' ' + opsKey
    ] || null;
  }
  if (!record && window.GAILS._opsAreaOnlyAssignmentLookup) {
    record = window.GAILS._opsAreaOnlyAssignmentLookup[opsKey] || null;
  }
  return record ? {
    region: record.region,
    opsArea: record.opsArea,
    baristas: record.baristas.map(function (entry) {
      return { name: entry.name, uid: entry.uid, homeBakery: entry.homeBakery };
    }),
    areaHeadBarista: record.areaHeadBarista,
    homeBakery: record.homeBakery
  } : null;
};

window.GAILS.getOpsAreaAssignmentsSnapshot = function () {
  return (window.GAILS.OPS_AREA_ASSIGNMENTS || []).map(function (record) {
    return {
      region: record.region,
      opsArea: record.opsArea,
      baristas: record.baristas.map(function (entry) {
        return { name: entry.name, uid: entry.uid, homeBakery: entry.homeBakery };
      }),
      areaHeadBarista: record.areaHeadBarista,
      areaHeadBaristaUid: record.areaHeadBaristaUid,
      homeBakery: record.homeBakery
    };
  });
};

