window.GAILS.ABS_BAND_RANGES = {
  'Exceeding': 'Benchmark Score 90–100',
  'Meeting': 'Benchmark Score 75–89',
  'Approaching': 'Benchmark Score 60–74',
  'Below Standard': 'Benchmark Score under 60',
  'Not Scored': 'No Benchmark Score for this period'
};

// ========== CEI WEIGHTS & BENCHMARKS ==========
window.GAILS.CEI_WEIGHTS = { nps: 0.20, ef: 0.20, dr: 0.20, fr: 0.20, time: 0.10, at: 0.10 };
window.GAILS.BENCHMARKS = { nps: 55, ef: 90, dr: 90, fr: 90, time: 70, at: 120 };
window.GAILS.BENCHMARK_FLOORS = { nps: 45, ef: 80, dr: 80, fr: 80, at: 125 };

// One shared RAG model for the league table, Focus review and KPI cards.
// Keeping these rules here prevents the same metric appearing with different
// colours in different parts of the dashboard.
window.GAILS.metricRagTone = function (metric, value) {
  if (value === null || value === undefined || isNaN(value)) return '';
  if (metric === 'n' || metric === 'nps' || metric === 'nc' || metric === 'nm' || metric === 'na') {
    return value >= 55 ? 'green' : value >= 45 ? 'amber' : 'red';
  }
  if (metric === 'dr' || metric === 'ef' || metric === 'fr' || metric === 'ov') {
    return value >= 90 ? 'green' : value >= 80 ? 'amber' : 'red';
  }
  if (metric === 'ts' || metric === 's2' || metric === 'time') {
    return value >= 70 ? 'green' : value >= 60 ? 'amber' : 'red';
  }
  if (metric === 'o5') return value <= 1 ? 'green' : value < 2.5 ? 'amber' : 'red';
  if (metric === 'at') {
    return value <= window.GAILS.BENCHMARKS.at ? 'green' : value < window.GAILS.BENCHMARK_FLOORS.at ? 'amber' : 'red';
  }
  return '';
};

window.GAILS.metricRagColor = function (metric, value) {
  var tone = window.GAILS.metricRagTone(metric, value);
  return tone ? 'var(--' + tone + ')' : 'var(--muted)';
};

window.GAILS.metricRagStyle = function (metric, value) {
  var tone = window.GAILS.metricRagTone(metric, value);
  return tone ? ' style="color:var(--' + tone + ')"' : '';
};

// Bar length expresses progress towards the benchmark, not peer percentile.
// Faster wait times are better, so that metric uses the inverse ratio.
window.GAILS.metricBenchmarkAttainment = function (metric, value, benchmark) {
  if (value === null || value === undefined || isNaN(value) || !benchmark || benchmark <= 0) return 0;
  var ratio = metric === 'at' ? benchmark / Math.max(1, value) : Math.max(0, value) / benchmark;
  return Math.max(0, Math.min(100, ratio * 100));
};

// ========== UTILITY ==========
